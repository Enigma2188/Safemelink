const assert = require('node:assert/strict');
const fs = require('node:fs');
const read = file => fs.readFileSync('scripts/' + file, 'utf8');
const sequential = read('test-phase13-development.sql');
const sqlOnly = sequential.replace(/--[^\n]*/g, '');
assert.match(sqlOnly, /^\s*begin;/);
assert.match(sqlOnly, /rollback;\s*$/);
assert.doesNotMatch(sqlOnly.replace(/\bon commit drop\b/gi, ''), /\bcommit\b/i);
assert.doesNotMatch(sqlOnly.replace(/'(?:''|[^'])*'/g, "''"), /\bexecute\b|\bcall\b|dblink|pg_notify|lo_export/i);
assert.match(sequential, /verified_ref text := null; workers_stopped boolean := false/);
assert.match(sequential, /is distinct from 'lwkxufnbjrpsehdkfmgy'/);
assert.match(sequential, /is distinct from true/);
assert.match(sequential, /gen_random_uuid\(\)/);
assert.doesNotMatch(sequential, /prepare_sos_delivery|net\.|http|cron\.schedule|sendSMS/);
assert.match(sequential, /j is null or j->>'ice_name' is distinct from/);
assert.match(sequential, /set local role anon/);
assert.match(sequential, /set local role authenticated/);
assert.match(sequential, /Synthetic legacy \+3900000000/);
const setup = read('phase13-concurrency-setup.sql');
assert.match(setup, /verified_ref text := null; workers_stopped boolean := false/);
assert.match(setup, /Existing fixture: inspect, do not overwrite/);
assert.match(setup, /commit;\s*$/);
